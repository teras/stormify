CREATE TABLE users (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR2(40) NOT NULL,
    email VARCHAR2(255),
    password_hash VARCHAR2(120) NOT NULL,
    active NUMBER(1) DEFAULT 1
)
/
CREATE TABLE products (
    sku VARCHAR2(20) PRIMARY KEY,
    name VARCHAR2(120) NOT NULL,
    description CLOB,
    price NUMBER(14,2),
    weight_kg NUMBER(11,3)
)
/
CREATE TABLE orders (
    id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer NUMBER(19) NOT NULL,
    total_amount NUMBER(14,2),
    tax_amount NUMBER(14,2)
)
/
CREATE TABLE legacy_carts (
    cart_id NUMBER(10) PRIMARY KEY,
    user_id NUMBER(10),
    created_at TIMESTAMP
)
/
CREATE TABLE audit_events (
    event_id NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payload CLOB
)
/
CREATE SEQUENCE invoice_seq START WITH 1000 INCREMENT BY 1
