package test.jpa

import javax.persistence.Column
import javax.persistence.Entity
import javax.persistence.EnumType
import javax.persistence.Enumerated
import javax.persistence.GeneratedValue
import javax.persistence.GenerationType
import javax.persistence.Id
import javax.persistence.JoinColumn
import javax.persistence.SequenceGenerator
import javax.persistence.Table
import javax.persistence.Transient

enum class JpaStatus { OPEN, CLOSED }

/** Table name from `@Table`; sequence by `sequenceName`, not by the generator name. */
@Entity(name = "OrderEntityName")
@Table(name = "jpa_orders")
class JpaOrder {
    @Id
    @SequenceGenerator(name = "ORDER_GEN", sequenceName = "jpa_order_seq", allocationSize = 1)
    @GeneratedValue(strategy = GenerationType.SEQUENCE, generator = "ORDER_GEN")
    @Column(name = "order_id")
    var id: Long? = null

    @Column(name = "order_code", insertable = false)
    var code: String? = null

    @Column(name = "created_by", updatable = false)
    var createdBy: String? = null

    @JoinColumn(name = "customer_id", insertable = false, updatable = false)
    var customer: JpaCustomer? = null

    @Enumerated(EnumType.STRING)
    var status: JpaStatus? = null

    @Transient
    var scratch: String? = null

    /** A name the generated literal must escape: `$` and a Greek letter. */
    @Column(name = "price\$ε")
    var price: Int? = null
}

/** Table name from `@Entity(name)` when there is no `@Table`; key generated by IDENTITY. */
@Entity(name = "jpa_customer_by_entity")
class JpaCustomer {
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    var id: Int? = null

    var name: String? = null
}

/** An enum and an entity whose generated registration names once collided ("registerEnumStatus"). */
enum class Status { NEW, DONE }

@Entity(name = "enum_status")
class EnumStatus {
    @Id
    var id: Int? = null

    @Enumerated(EnumType.STRING)
    var status: Status? = null
}
